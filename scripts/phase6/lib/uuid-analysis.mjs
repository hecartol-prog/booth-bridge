/** RFC 4122 UUID (any version 1–5). Suitable for Postgres uuid columns. */
export const UUID_RFC4122_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/**
 * Lenient hyphenated 128-bit hex (8-4-4-4-12).
 * Catches non-standard variant/version nibbles for investigation.
 */
export const UUID_HYPHENATED_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** MongoDB ObjectId style (24 hex chars) — used by Base44 app IDs, not necessarily entity IDs. */
export const OBJECT_ID_RE = /^[0-9a-f]{24}$/i;

export const PRIMARY_UUID_REGEX = UUID_RFC4122_RE;
export const PRIMARY_UUID_REGEX_NAME = "UUID_RFC4122_RE";

/**
 * @param {unknown} value
 * @param {RegExp} regex
 */
export function matchesRegex(value, regex) {
  return typeof value === "string" && regex.test(value.trim());
}

/**
 * Analyze `id` field across sampled rows.
 * @param {string} entityName
 * @param {Array<Record<string, unknown>>} rows
 */
export function analyzeEntityIds(entityName, rows) {
  const totalSampled = rows.length;
  let uuidCount = 0;
  let nonUuidCount = 0;
  let missingIdCount = 0;
  const nonUuidExamples = [];

  for (const row of rows) {
    const id = row?.id;
    if (id === null || id === undefined || id === "") {
      missingIdCount += 1;
      nonUuidCount += 1;
      continue;
    }
    if (matchesRegex(id, UUID_RFC4122_RE)) {
      uuidCount += 1;
    } else {
      nonUuidCount += 1;
      if (nonUuidExamples.length < 5) {
        nonUuidExamples.push(String(id));
      }
    }
  }

  const validIdCount = totalSampled - missingIdCount;
  const uuidPct = validIdCount > 0 ? (uuidCount / validIdCount) * 100 : 0;

  let classification;
  let confidence;

  if (totalSampled === 0) {
    classification = "inconclusive_empty";
    confidence = "none";
  } else if (missingIdCount === totalSampled) {
    classification = "ids_require_remapping";
    confidence = "high";
  } else if (uuidCount === validIdCount) {
    classification = "ids_are_uuid";
    confidence = totalSampled >= 10 ? "high" : "medium";
  } else if (uuidCount === 0) {
    classification = "ids_require_remapping";
    confidence = totalSampled >= 10 ? "high" : "medium";
  } else {
    classification = "ids_are_mixed";
    confidence = totalSampled >= 10 ? "high" : "medium";
  }

  return {
    entity: entityName,
    totalSampled,
    uuidCount,
    nonUuidCount,
    missingIdCount,
    uuidPercentage: Math.round(uuidPct * 100) / 100,
    regexUsed: PRIMARY_UUID_REGEX_NAME,
    regexPattern: UUID_RFC4122_RE.source,
    classification,
    confidence,
    nonUuidExamples,
  };
}

/**
 * @param {Array<ReturnType<typeof analyzeEntityIds>>} perEntity
 */
export function buildCompatibilitySummary(perEntity) {
  const withData = perEntity.filter((e) => e.totalSampled > 0);
  const allUuid = withData.every((e) => e.classification === "ids_are_uuid");
  const anyMixed = withData.some((e) => e.classification === "ids_are_mixed");
  const anyRemap = withData.some(
    (e) =>
      e.classification === "ids_require_remapping" ||
      e.classification === "ids_are_mixed"
  );
  const emptyCount = perEntity.filter((e) => e.totalSampled === 0).length;

  let recommendation;
  if (withData.length === 0) {
    recommendation = "INCONCLUSIVE — no sample data returned; run export against production before deciding.";
  } else if (allUuid && !anyMixed) {
    recommendation = "Preserve IDs directly — all sampled entities are 100% RFC 4122 UUID compatible.";
  } else if (anyMixed || anyRemap) {
    recommendation =
      "Generate UUID remapping tables for non-UUID entities; preserve UUID rows directly where classification is ids_are_uuid.";
  } else {
    recommendation = "INCONCLUSIVE — review per-entity report.";
  }

  return {
    entitiesAnalyzed: perEntity.length,
    entitiesWithData: withData.length,
    entitiesEmpty: emptyCount,
    allUuidCompatible: allUuid && withData.length > 0,
    anyMixed,
    anyRemap,
    recommendation,
  };
}

/**
 * @param {Array<ReturnType<typeof analyzeEntityIds>>} perEntity
 * @param {ReturnType<typeof buildCompatibilitySummary>} summary
 */
export function formatUuidReportMarkdown(perEntity, summary) {
  const lines = [
    "# Phase 6 — UUID Compatibility Report",
    "",
    `**Status:** Generated by \`verify-uuid-sample.mjs\` — do not treat as final until run against production.`,
    "",
    "## Summary recommendation",
    "",
    summary.recommendation,
    "",
    "## Per-entity analysis",
    "",
    "| Entity | Sampled | UUID | Non-UUID | Missing ID | UUID % | Classification | Confidence |",
    "|--------|---------|------|----------|------------|--------|----------------|------------|",
  ];

  for (const row of perEntity) {
    const label =
      row.classification === "ids_are_uuid"
        ? "UUID compatible"
        : row.classification === "ids_are_mixed"
          ? "Mixed"
          : row.classification === "ids_require_remapping"
            ? "Requires remapping"
            : "Inconclusive (empty)";
    lines.push(
      `| ${row.entity} | ${row.totalSampled} | ${row.uuidCount} | ${row.nonUuidCount} | ${row.missingIdCount} | ${row.uuidPercentage}% | ${label} | ${row.confidence} |`
    );
  }

  lines.push("", "## Regex used", "", `- **Primary:** \`${PRIMARY_UUID_REGEX_NAME}\` → \`${UUID_RFC4122_RE.source}\``, "");
  lines.push("## Non-UUID examples (first 5 per entity)", "");

  for (const row of perEntity) {
    if (row.nonUuidExamples.length > 0) {
      lines.push(`### ${row.entity}`, "");
      for (const ex of row.nonUuidExamples) {
        lines.push(`- \`${ex}\``);
      }
      lines.push("");
    }
  }

  return lines.join("\n");
}
